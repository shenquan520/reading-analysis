def _width_report(idx, ap):
    """诊断（非门禁）：关闸跑，看哪些关键词是「概念名/提示词」而非「自述说法」。

    这些词对 agent 是有用提示，不该删；这里只是把宽度**显性化**，
    方便判断某个词有没有必要补一个更贴近口语的自述变体。
    """
    probes = NEUTRAL_KEYWORD_WIDTH + ['我想知道转折是什么意思', '这段的让步是什么作用']
    hits = []
    for t in probes:
        got = ap.match(t, idx, gate=False)
        if got:
            hits.append((t, got))
    print()
    print(f"  ℹ️ 宽度诊断（关闸，非门禁）：{len(hits)}/{len(probes)} 条会被宽关键词打中")
    print("     这些是概念名/提示词的正常表现——闸门负责在生产中挡住它们")
    return True


def _selftest():
    import importlib.util, os
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location("ap", os.path.join(here, "anti_patterns.py"))
    ap = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ap)
    idx = ap.load_index(ap.index_path(os.path.dirname(here)))

    def run(name, cases, should_hit, gate=True):
        miss = [t for t in cases if bool(ap.match(t, idx, gate=gate)) != should_hit]
        flag = "✅" if not miss else "❌"
        print(f"  {flag} {name:26} {len(cases) - len(miss)}/{len(cases)}")
        for t in miss[:6]:
            got = ap.match(t, idx, gate=gate)
            print(f"        {'漏' if should_hit else '误'}：{t} -> {got or '（空）'}")
        return not miss

    print("反模式匹配回归套件（生产口径：开闸）")
    print("=" * 70)
    ok = True
    ok &= run("历史失败用例（必须命中）", HISTORY, True)
