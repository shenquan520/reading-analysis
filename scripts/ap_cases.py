def _width_report(idx, ap):
    """诊断（非门禁）：关闸跑，看哪些关键词是「概念名/提示词」而非「自述说法」。

    这些词对 agent 是有用提示，不该删；这里只是把宽度**显性化**，
    方便判断某个词有没有必要补一个更贴近口语的自述变体。
    """
    probes = NEUTRAL_KEYWORD_WIDTH + ['我想知道转折是什么意思', '这段的让步是什么作用']
    hits = []
    for t in probes:
        got = ap.match(t, idx, gate=False)
        if got:
            hits.append((t, got))
    print()
    print(f"  ℹ️ 宽度诊断（关闸，非门禁）：{len(hits)}/{len(probes)} 条会被宽关键词打中")
    print("     这些是概念名/提示词的正常表现——闸门负责在生产中挡住它们")
    return True


def _selftest():
    import importlib.util, os
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location("ap", os.path.join(here, "anti_patterns.py"))
    ap = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ap)
    idx = ap.load_index(ap.index_path(os.path.dirname(here)))

    def run(name, cases, should_hit, gate=True):
        miss = [t for t in cases if bool(ap.match(t, idx, gate=gate)) != should_hit]
        flag = "✅" if not miss else "❌"
        print(f"  {flag} {name:26} {len(cases) - len(miss)}/{len(cases)}")
        for t in miss[:6]:
            got = ap.match(t, idx, gate=gate)
            print(f"        {'漏' if should_hit else '误'}：{t} -> {got or '（空）'}")
        return not miss

    print("反模式匹配回归套件（生产口径：开闸）")
    print("=" * 70)
    ok = True
    ok &= run("历史失败用例（必须命中）", HISTORY, True)
    ok &= run("实战自述（必须命中）", SELF_REPORT, True)
    print("  --- 误报侧（必须为空）---")
    ok &= run("内容描述·本机", NEUTRAL_DESC, False)
    ok &= run("内容描述·审核方", NEUTRAL_REVIEWER, False)
    ok &= run("内容描述·加固", NEUTRAL_HARD, False)
    ok &= run("关键词宽度试纸", NEUTRAL_KEYWORD_WIDTH, False)
    ok &= run("已发生过的真实误报", REGRESSED_FP, False)
    print("  --- 误报侧·「有自述信号 × 含错因词汇」格（第七轮 L2 新增，原先空白）---")
    ok &= run("评价文章·报告 8 条", NEUTRAL_EVAL, False)
    ok &= run("评价文章·他方 6 条", NEUTRAL_EVAL_OK, False)
    print("  --- 防御·自述里合法提到段落（施事判定最容易误伤这一格）---")
    ok &= run("自述 + 对象词", SELF_WITH_OBJECT, True)
    _width_report(idx, ap)
    if DELIBERATE_SKIP:
        print()
        print(f"  ℹ️ 有意不弹 {len(DELIBERATE_SKIP)} 条（设计决定，非漏报）——别去「修」它：")
        for t, why in DELIBERATE_SKIP.items():
            print(f"     · {t}：{why}")
    print("=" * 70)
    print("结论：", "🟢 全绿" if ok else "🔴 有不过")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(_selftest())
